import { Diagnostic, IngressIR, IngressRoute } from '../ir/types';
import { ProxyAdapter } from './types';

export const nginxAdapter: ProxyAdapter = {
  id: 'nginx-conf',
  name: 'NGINX',
  vendor: 'NGINX Open Source / Plus',
  format: 'conf',
  fileName: 'nginx.conf',
  description: 'Compiles canonical IR into NGINX server, upstream, and split_clients blocks.',
  capabilities: {
    supportsWeightedCanary: true,
    supportsGrpc: true,
    supportsMtls: true,
    supportsConsistentHash: true,
    supportsCustomPlugins: true,
  },
  compile(ir: IngressIR): string {
    const lines: string[] = [
      `# Generated by IngressOS Control Plane (${ir.clusterName})`,
      `worker_processes auto;`,
      `events { worker_connections 4096; }`,
      ``,
      `http {`,
    ];

    // Upstream blocks
    for (const ups of Object.values(ir.upstreams)) {
      lines.push(`  upstream ${ups.name.replace(/[^a-zA-Z0-9_-]/g, '_')} {`);
      if (ups.lbAlgorithm === 'least_conn') lines.push(`    least_conn;`);
      if (ups.lbAlgorithm === 'consistent_hash') {
        const hdr = ups.hashHeader ? `$http_${ups.hashHeader.toLowerCase().replace(/-/g, '_')}` : '$request_uri';
        lines.push(`    hash ${hdr} consistent;`);
      }
      for (const ep of ups.endpoints) {
        const stateFlag = ep.healthy ? '' : ' down';
        lines.push(`    server ${ep.address}:${ep.port} max_fails=${ups.circuitBreaker.maxErrors} fail_timeout=${Math.round(ups.circuitBreaker.resetTimeoutMs / 1000)}s${stateFlag}; # ${ep.region}`);
      }
      lines.push(`  }`);
      lines.push(``);
    }

    const activeRoutes = ir.routeOrder
      .map((id) => ir.routes[id])
      .filter((r): r is IngressRoute => Boolean(r) && r.enabled);

    // Split clients for multi-target canary routes
    for (const rt of activeRoutes) {
      if (rt.targets.length > 1) {
        const splitVar = `$upstream_${rt.name.replace(/[^a-zA-Z0-9_]/g, '_')}`;
        lines.push(`  split_clients "\${remote_addr}\${request_uri}" ${splitVar} {`);
        rt.targets.forEach((t, idx) => {
          const upsName = ir.upstreams[t.upstreamId]?.name.replace(/[^a-zA-Z0-9_-]/g, '_') ?? t.upstreamId;
          const pct = idx === rt.targets.length - 1 ? '*' : `${t.weight}%`;
          lines.push(`    ${pct} ${upsName};`);
        });
        lines.push(`  }`);
        lines.push(``);
      }
    }

    // Server blocks per listener
    for (const lst of Object.values(ir.listeners)) {
      const cert = lst.tlsCertId ? ir.certificates[lst.tlsCertId] : undefined;
      const lstRoutes = activeRoutes
        .filter((r) => r.listenerId === lst.id)
        .sort((a, b) => b.priority - a.priority);

      const sslFlag = lst.protocol === 'HTTPS' || lst.protocol === 'GRPC' ? ' ssl' : '';
      const http2Flag = lst.protocol === 'GRPC' ? ' http2' : '';

      lines.push(`  server {`);
      lines.push(`    listen ${lst.port}${sslFlag}${http2Flag};`);
      lines.push(`    server_name ${lst.hostnames.join(' ') || '_'};`);
      if (cert) {
        lines.push(`    ssl_certificate /etc/nginx/certs/${cert.name}.crt;`);
        lines.push(`    ssl_certificate_key /etc/nginx/certs/${cert.name}.key;`);
        if (lst.tlsMode === 'mutual') {
          lines.push(`    ssl_verify_client on;`);
        }
      }
      lines.push(``);

      for (const rt of lstRoutes) {
        const locPrefix = rt.matchType === 'exact' ? '= ' : rt.matchType === 'regex' ? '~ ' : '';
        lines.push(`    location ${locPrefix}${rt.pathPrefix} {`);
        lines.push(`      # Host: ${rt.host} | Priority: ${rt.priority}`);
        for (const mw of rt.middlewares) {
          if (!mw.enabled) continue;
          if (mw.pluginId === 'rate-limit') {
            lines.push(`      limit_req_status ${String(mw.config.statusCode ?? 429)}; # ${String(mw.config.requestsPerSecond ?? 250)} r/s`);
          } else if (mw.pluginId === 'header-transform') {
            if (mw.config.addHeaderKey) {
              lines.push(`      proxy_set_header ${String(mw.config.addHeaderKey)} "${String(mw.config.addHeaderValue ?? '')}";`);
            }
          } else if (mw.pluginId === 'cors') {
            lines.push(`      add_header Access-Control-Allow-Origin "${String(mw.config.allowedOrigins ?? '*')}";`);
          } else {
            lines.push(`      # middleware: ${mw.pluginId} ${JSON.stringify(mw.config)}`);
          }
        }
        const policy = rt.policyId ? ir.policies[rt.policyId] : undefined;
        if (policy) {
          lines.push(`      proxy_read_timeout ${Math.ceil(policy.timeoutMs / 1000)}s;`);
        }
        const targetExpr =
          rt.targets.length > 1
            ? `$upstream_${rt.name.replace(/[^a-zA-Z0-9_]/g, '_')}`
            : ir.upstreams[rt.targets[0]?.upstreamId ?? '']?.name.replace(/[^a-zA-Z0-9_-]/g, '_') ?? 'default';

        if (lst.protocol === 'GRPC') {
          lines.push(`      grpc_pass grpcs://${targetExpr};`);
        } else {
          lines.push(`      proxy_pass http://${targetExpr};`);
        }
        lines.push(`    }`);
      }

      lines.push(`  }`);
      lines.push(``);
    }

    lines.push(`}`);
    return lines.join('\n');
  },
  validate(ir: IngressIR): Diagnostic[] {
    const diags: Diagnostic[] = [];
    for (const rt of Object.values(ir.routes)) {
      if (rt.enabled && rt.methods.length > 0 && !rt.methods.includes('*') && rt.methods.length < 4) {
        diags.push({
          id: `diag-nginx-methods-${rt.id}`,
          severity: 'info',
          category: 'adapter-capability',
          entityType: 'route',
          entityId: rt.id,
          message: `NGINX adapter notes method filter [${rt.methods.join(', ')}] on "${rt.name}" compiles via limit_except`,
          detail: 'Method-scoped NGINX locations use limit_except directives in production.',
        });
      }
    }
    return diags;
  },
};
